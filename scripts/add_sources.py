def insert(path, mapping):
    with open(path, encoding="utf-8") as fh:
        lines = fh.read().split("\n")

    # کۆتاییی هەر بەشێک: ڕاستەوخۆ پێش سەردێڕی دواتر
    heads = [i for i, ln in enumerate(lines)
             if ln.startswith("@H1 ") or ln.startswith("@PART ")]
    out, done = [], 0

    for idx, ln in enumerate(lines):
        # ئایا لێرەدا بەشێک کۆتایی دێت کە سەرچاوەی هەیە؟
        if idx in heads:
            for h, items in mapping.items():
                hi = next((j for j in heads if lines[j].strip() == h), None)
                if hi is not None and hi < idx:
                    nxt = next((j for j in heads if j > hi), len(lines))
                    if nxt == idx:
                        out.append("@SRC")
                        out.extend(items)
                        out.append("@ENDSRC")
                        out.append("")
                        done += 1
        out.append(ln)

    # بەشی کۆتایی فایلەکە
    for h, items in mapping.items():
        hi = next((j for j in heads if lines[j].strip() == h), None)
        if hi is not None and not any(j > hi for j in heads):
            out.append("")
            out.append("@SRC")
            out.extend(items)
            out.append("@ENDSRC")
            done += 1

    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    return done


